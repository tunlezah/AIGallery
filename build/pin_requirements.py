#!/usr/bin/env python3
"""Regenerate build/requirements.txt from build/requirements.in with sha256 hashes.

pip enters hash-checking mode as soon as any requirement carries --hash, and
then refuses any file whose hash is not listed. Every file PyPI publishes for
a pinned version is listed (all wheels + sdist), so pip can still pick the
right wheel for any platform or Python version.

Needs network access to pypi.org: run it on a connected machine when bumping
a version, then commit both files. On a disconnected GitLab instance, pip
must be pointed at a mirror that serves the unmodified PyPI files (a caching
proxy such as Nexus or Artifactory does); rebuilt or re-packaged wheels will
not match and are refused, which is the point.
"""

from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
PINS = HERE / "requirements.in"
OUT = HERE / "requirements.txt"
PYPI = "https://pypi.org/pypi/{name}/{version}/json"


def read_pins() -> list[tuple[str, str]]:
    pins = []
    for raw in PINS.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        name, sep, version = line.partition("==")
        if not sep or not version.strip():
            sys.exit(f"error: {line!r} in {PINS.name} must pin an exact version with ==")
        pins.append((name.strip(), version.strip()))
    return pins


def main() -> int:
    lines = [
        "# GENERATED by build/pin_requirements.py from build/requirements.in; do not edit by hand.",
        "# Every requirement carries sha256 hashes, so pip runs in hash-checking mode and",
        "# refuses any file that does not match one of them.",
        "",
    ]
    for name, version in read_pins():
        with urllib.request.urlopen(PYPI.format(name=name, version=version), timeout=60) as response:
            data = json.load(response)
        hashes = sorted({entry["digests"]["sha256"] for entry in data.get("urls", [])})
        if not hashes:
            sys.exit(f"error: PyPI lists no files for {name}=={version}")
        lines.append(f"{name}=={version} \\")
        for index, digest in enumerate(hashes):
            tail = " \\" if index < len(hashes) - 1 else ""
            lines.append(f"    --hash=sha256:{digest}{tail}")
        lines.append("")
        print(f"{name}=={version}: {len(hashes)} file hash(es)")
    OUT.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
